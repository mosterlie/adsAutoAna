# -*- coding: utf-8 -*-
"""深度检测提示词(统一口径)

★ 总目的(所有提示词的唯一出发点):
   判断「某个搜索词在亚马逊的搜索结果集」与「我的这个商品」是**不是同一类东西**。
   结果集匹配度低 → 该词带来的流量与我的品无关 → 后续考虑**否定该词**。

所以三个层次的判断都必须回答同一个问题, 只是粒度不同:
   ① 词级  TERM_VERDICT : 这个词的用户搜索意图 vs 我的品      → 词要不要留
   ② 标题级 TITLE_PAIR  : 我的标题 vs 某条竞品标题是否同类     → 结果集里有多少同类
   ③ 图片级 IMAGE_PAIR  : 我的主图 vs 某条竞品主图是否同类     → 视觉上像不像

统一评分标尺(RUBRIC)—— 三个提示词共用, 保证分数可比:
   90-100  同一品类, 核心用途一致, 基本可互换
   70-89   同一大类, 细分规格/形态不同(同用途)
   40-69   相关但用途不同: 上下位词、配套件、同场景不同物
   10-39   弱相关: 仅个别属性沾边(材质/颜色/场合)
   0-9     完全无关: 不同类物品
"""

#: 三个提示词共用的评分标尺文本
RUBRIC = """评分标尺(0-100):
- 90-100: 同一品类, 核心用途一致, 基本可互换
- 70-89 : 同一大类, 细分规格/形态不同, 但用途相同
- 40-69 : 相关但用途不同(上下位词 / 配套件 / 同场景不同物)
- 10-39 : 弱相关, 仅个别属性沾边(材质 / 颜色 / 使用场合)
- 0-9   : 完全无关, 属不同类物品"""

#: 两个标题提示词共用的「忽略项」说明 —— 只比物品本身
IGNORE_RULE = """比较时【只看物品类别与用途】:
- 忽略: 品牌 / 型号 / 尺寸规格 / 颜色 / 数量包装 / 材质差异 / 卖点词 / 赠品配件 /
  促销词(人気・新品・送料無料等) / 标题堆词与语序差异
- 例: "1個柵金網フェンス 菱形ワイヤーメッシュ 防獣フェンス 亜鉛めっき材" 
      ≈ "菱形金網フェンス 2m 黒" → 同为「菱形铁丝网围栏」→ 同类
- 例: "ガスコンロ 多機能キッチンコンロ" 
      vs "金網フェンス 防獣フェンス" → 燃气灶 vs 围栏网 → 不同类"""


# ---------------------------------------------------------------------------
# ① 词级: 搜索词意图 vs 我的商品  (决定该词留存/否定)
# ---------------------------------------------------------------------------
TERM_VERDICT_PROMPT = """你是亚马逊广告的「搜索词否定」决策助手。

【任务】判断: 用户搜索下面这个词时想买的商品类型, 与「我的商品」是不是同一类物品。
这决定了这个词的流量是否值得保留。

{rubric}

{ignore}

【额外判断】
- 若搜索词是具体另一类物品(与我的品不同类) → 低分
- 若搜索词是我的品类的通用词 / 同类词 / 上位词 → 高分
- 若搜索词含我的品类词但限定成了别的用途或对象(如"宠物用防音室"vs通用防音室) → 中等分
- 若搜索词是乱码、纯型号(如 ASIN、B0xxxxxxx)、品牌名等无品类含义的词 → reason 里说明"无品类含义"

搜索词：{term}

我的商品标题：{my_title}

只输出 JSON：{{"score":0-100整数,"same_category":true或false,"term_intent":"这个词想买什么(≤15字)","reason":"≤30字中文理由"}}"""


# ---------------------------------------------------------------------------
# ② 标题级: 我的标题 vs 竞品标题 (逐条, 汇总成结果集匹配率)
# ---------------------------------------------------------------------------
TITLE_PAIR_PROMPT = """判断下面两个商品标题是不是**同一类物品**(同品类、同用途)。

{rubric}

{ignore}

标题A(我的商品)：{a}
标题B(竞品)：{b}

先各自在心里提炼「核心品类词」, 再比较。只输出 JSON：
{{"score":0-100整数,"same_category":true或false,"core_a":"A的核心品类词(≤10字)","core_b":"B的核心品类词(≤10字)","reason":"≤30字中文理由"}}"""


# ---------------------------------------------------------------------------
# ③ 图片级: 我的主图 vs 竞品主图 (逐条, 视觉上确认是否同类)
# ---------------------------------------------------------------------------
IMAGE_PAIR_PROMPT = """图1是「我的商品」的主图，图2是用户在亚马逊搜索该关键词时看到的一条竞品主图。

【任务】判断这两个商品是不是同一类物品(同品类、同用途、外观结构一致)。

{rubric}

只看物品本身: 忽略背景、拍摄角度、光源、水印、促销角标、尺寸标注文字。
若只是同材质/同颜色但属不同类物品 → 低分; 若同类但规格或款式略有差异 → 70-89。

只输出 JSON：{{"score":0-100整数,"same_category":true或false,"reason":"≤30字中文理由"}}"""


def render(tpl: str, **kw) -> str:
    """填充 {rubric}/{ignore}/业务字段"""
    return tpl.format(rubric=RUBRIC, ignore=IGNORE_RULE, **kw)
